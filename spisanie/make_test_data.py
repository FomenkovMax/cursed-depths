def make_postanovlenie_text(row: list, scenario: str) -> str:
    id_nomer, ip_nomer, data_okonchaniya, id_data, fio, dr, kod_kredita, _, vozbuzhdenie = row

    fio_v_dokumente = fio
    if scenario == "genitive":
        fio_v_dokumente = to_genitive(fio)
    if scenario == "wrong_dr":
        dr = dr.replace(year=dr.year - 1)
    if scenario == "wrong_end":
        data_okonchaniya = data_okonchaniya + dt.timedelta(days=9)

    ustanovil, osnovanie = USTANOVIL_DEFAULT, OSNOVANIE_P4
    if scenario == "no_property_marker":
        ustanovil = USTANOVIL_NO_MARKER
    if scenario == "punkt1":
        ustanovil, osnovanie = USTANOVIL_PUNKT1, OSNOVANIE_P1

    return POSTANOVLENIE.format(
        ip_nomer=ip_nomer,
        data_vozbuzhdeniya=vozbuzhdenie.strftime("%d.%m.%Y"),
        data_okonchaniya=data_okonchaniya.strftime("%d.%m.%Y"),
        id_nomer=id_nomer,
        id_data=id_data.strftime("%d.%m.%Y"),
        fio_v_dokumente=fio_v_dokumente,
        data_rozhdeniya=dr.strftime("%d.%m.%Y"),
        kod_kredita=kod_kredita,
        ustanovil=ustanovil,
        osnovanie_text=osnovanie,
    )


def to_genitive(fio: str) -> str:
    """Грубое склонение в родительный падеж — только для тестовых документов."""
    def word(w: str) -> str:
        if w.endswith("ова") or w.endswith("ева") or w.endswith("ина"):
            return w[:-1] + "ой"
        if w.endswith("а"):
            return w[:-1] + "ы"
        if w.endswith("я"):
            return w[:-1] + "и"
        if w.endswith("ий") or w.endswith("ый"):
            return w[:-2] + "ого"
        if w.endswith("ь"):
            return w[:-1] + "я"
        return w + "а"
    return " ".join(word(w) for w in fio.split())



def write_registry(path: Path, headers: list[str], rows: list) -> None:
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "Реестр"
    sheet.append(headers + ["Ожидаемый результат (только для теста)"])
    for values, comment in rows:
        sheet.append(list(values) + [comment])
    for index, _ in enumerate(headers, start=1):
        sheet.column_dimensions[chr(64 + index)].width = 22
    workbook.save(path)


def write_txt(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8")


def write_docx(path: Path, text: str) -> None:
    import docx

    document = docx.Document()
    for line in text.split("\n"):
        document.add_paragraph(line)
    document.save(str(path))


def write_pdf(path: Path, text: str) -> None:
    """PDF с текстовым слоем (DejaVu — в ней есть кириллица)."""
    import pymupdf

    import textwrap

    document = pymupdf.open()
    font_path = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

    # Переносим по ширине страницы: без этого длинный абзац уезжает за край,
    # хвост в текстовый слой не попадает и тестовый PDF перестаёт быть похожим
    # на настоящее постановление.
    lines: list[str] = []
    for line in text.split("\n"):
        lines.extend(textwrap.wrap(line, width=92) or [""])
    per_page = 52

    for start in range(0, len(lines), per_page):
        page = document.new_page(width=595, height=842)
        page.insert_font(fontname="dejavu", fontfile=font_path)
        y = 56
        for line in lines[start:start + per_page]:
            page.insert_text((48, y), line, fontname="dejavu", fontsize=9)
            y += 14
    document.save(str(path))
    document.close()


def write_scan_pdf(path: Path) -> None:
    """PDF без текстового слоя — имитация скана."""
    import pymupdf

    document = pymupdf.open()
    page = document.new_page(width=595, height=842)
    page.draw_rect(pymupdf.Rect(40, 40, 555, 800), color=(0.75, 0.75, 0.75), width=1)
    for offset in range(0, 24):
        y = 80 + offset * 28
        page.draw_line(pymupdf.Point(60, y), pymupdf.Point(60 + (offset * 17) % 420, y),
                       color=(0.55, 0.55, 0.55), width=3)
    document.save(str(path))
    document.close()


def main() -> int:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "test_data")
    docs = out / "postanovleniya"
    docs.mkdir(parents=True, exist_ok=True)

    write_registry(out / "reestr_sid.xlsx", SID_HEADERS, SID_ROWS)
    write_registry(
        out / "reestr_st46.xlsx",
        ST46_HEADERS,
        [(row, comment) for row, _, comment in ST46_ROWS],
    )

    created = 0
    for row, scenario, _ in ST46_ROWS:
        ip_nomer = row[1]
        stem = ip_nomer.replace("/", "-").replace(" ", "-")

        if scenario == "missing":
            continue
        if scenario == "scan":
            write_scan_pdf(docs / f"{stem}.pdf")
            created += 1
            continue

        text = make_postanovlenie_text(row, scenario)
        if scenario == "ok_docx":
            write_docx(docs / f"{stem}.docx", text)
        elif scenario in {"ok", "genitive"}:
            write_pdf(docs / f"{stem}.pdf", text)
        else:
            write_txt(docs / f"{stem}.txt", text)
        created += 1

    # постановление-сирота: в реестре такой строки нет
    orphan = list(ST46_ROWS[0][0])
    orphan[1] = ORPHAN_IP
    orphan[4] = "Незнамов Пётр Петрович"
    write_txt(
        docs / f"{ORPHAN_IP.replace('/', '-')}.txt",
        make_postanovlenie_text(orphan, "ok"),
    )
    created += 1

    print(f"Готово. Отчётная дата тестового набора: {ON_DATE.strftime('%d.%m.%Y')}")
    print(f"  {out / 'reestr_sid.xlsx'}   — {len(SID_ROWS)} строк")
    print(f"  {out / 'reestr_st46.xlsx'}  — {len(ST46_ROWS)} строк")
    print(f"  {docs}  — {created} постановлений")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

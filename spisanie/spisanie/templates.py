def period_text(start, end) -> str:
    """«3 года 2 месяца 5 дней» между двумя датами — для текста суждения.

    Считаем календарём (relativedelta), а не делением на 365. Иначе ровно три
    года от 01.09.2023 до 01.09.2026 превращаются в «3 года 1 день», и суждение
    об отказе получает формулировку, противоречащую собственному выводу.
    """
    from dateutil.relativedelta import relativedelta

    delta = relativedelta(end, start)
    parts = []
    if delta.years:
        parts.append(f"{delta.years} {_form(delta.years, 'год', 'года', 'лет')}")
    if delta.months:
        parts.append(f"{delta.months} {_form(delta.months, 'месяц', 'месяца', 'месяцев')}")
    if delta.days or not parts:
        parts.append(f"{delta.days} {_form(delta.days, 'день', 'дня', 'дней')}")
    return " ".join(parts)


def _form(number: int, one: str, few: str, many: str) -> str:
    if 11 <= number % 100 <= 14:
        return many
    last = number % 10
    if last == 1:
        return one
    if 2 <= last <= 4:
        return few
    return many

/**
 * Комната трофеев — постоянная коллекция уникальных боссов, когда-либо поверженных игроком
 * (первый килл фиксируется в PlayerBossTrophy, см. combat/action.ts). Награда за НОВЫЙ трофей —
 * премиум-эксклюзив: F2P всё равно копит трофеи молча (просмотр коллекции свободен, как
 * Достижения/Кодекс), но золото и Осколки Короны за первый килл каждого босса достаются только
 * при активном премиуме в момент этого килла — покупка премиума позже не награждает задним
 * числом уже добытые трофеи, только будущие.
 *
 * Ограничение: трофей фиксируется только за победу через combat/action.ts (соло, данж, Бездна,
 * испытания) — party-бой (lib/party-combat-resolver.ts) сюда намеренно не подключён, это
 * отдельная более сложная система без собственного премиум-множителя золота/опыта; тех же
 * боссов всегда можно взять соло, так что трофей не заблокирован полностью.
 */

import { ENEMIES } from './game-data';

export function bossEnemies() {
  return ENEMIES.filter(e => e.isBoss);
}


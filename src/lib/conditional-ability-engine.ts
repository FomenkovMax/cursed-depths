/**
 * Активные способности с условным/отложенным триггером, которые
 * resolveAbility() в combat-engine.ts не умеет разрешать — он резолвит
 * КАЖДУЮ активную способность как "мгновенный эффект по клику сейчас", что
 * для двух узких категорий текста противоречит их описанию (и до этого
 * модуля приводило не просто к "декоративности", а к ЯВНО НЕВЕРНОМУ
 * поведению — напр. "Снижает урон следующего удара врага на 40%" содержит
 * "снижа", поэтому classifyEffect() относил её к 'debuff' и она ослабляла
 * УРОН ВРАГА, а не входящий урон ИГРОКА — прямо противоположно описанию):
 *
 * 1. "Обереги от смерти" (death ward) — "1 раз за бой при получении
 *    смертельного урона/при смертельном ударе выживает с 1 ХП..." — эти
 *    способности НЕ кастуются игроком вообще, они всегда "заряжены" (как
 *    пассивка) и срабатывают автоматически в момент, когда игрок должен
 *    был умереть. Резолвятся так же, как пассивка death_save (Феникс,
 *    lib/passive-engine.ts), только источник — активная способность класса.
 *    combat/action/route.ts отклоняет их ручной каст, а getAvailableAbilities
 *    в page.tsx вообще не показывает их в списке кастуемых.
 *
 * 2. "Заряженные" одноразовые эффекты — "снижает урон СЛЕДУЮЩЕГО удара
 *    врага на N%" / "СЛЕДУЮЩАЯ атака наносит +N% урона" и т.п. Такие
 *    способности игрок ДЕЙСТВИТЕЛЬНО кастует в свой ход (тратит ману), но
 *    эффект не применяется сейчас — он "заряжается" и ждёт следующего
 *    relevant события (следующий входящий удар врага ИЛИ следующая
 *    атака/способность игрока), см. lib/combat-effects.ts ArmedEffectKind.
 *    Условные варианты ("если убивает" — эффект зависит от исхода ЭТОЙ ЖЕ
 *    атаки, не безусловный заряд) и повторяющиеся ("каждые N ударов" — не
 *    одноразовый заряд, а рекуррентный триггер) намеренно исключены —
 *    разбор ниже не пытается угадать их семантику.
 *
 * 3. "Мгновенный самобафф этого каста" — "Игнорирует N% брони [+
 *    гарантированный крит] (КД N ходов)" — в отличие от категории 2, эффект
 *    относится к ЭТОМУ САМОМУ касту, не к следующему. КД (кулдаун) —
 *    отдельная новая механика (bossState.abilityCooldowns), т.к. до этого
 *    модуля способностей с перезарядкой в движке не существовало вообще —
 *    любая открытая по уровню способность была кастуема каждый ход, пока
 *    хватало маны.
 *
 * 4. "Мгновенная казнь" — "Если у врага ниже N% ХП — мгновенная казнь
 *    (PvE: порог M%, казнь только не-боссов; PvP: ...)". В этой
 *    однопользовательской игре нет PvP, поэтому PvP-ветка игнорируется;
 *    PvE-порог и оговорка "только не-боссов" в самом тексте способности —
 *    берутся как есть, боссов казнь никогда не касается.
 *
 * 5. "Активированный контрудар после блока" (retaliation-hammer,
 *    counter-blow) — "После блокировки/блока удара наносит контрудар
 *    равный N% поглощённого" — в отличие от ОДНОИМЁННЫХ ПАССИВОК
 *    tornak-foundation/bone-spike (см. lib/passive-runtime.ts
 *    onBlockHealPercent/onBlockCounterPercent, которые действуют всегда),
 *    здесь эффект нужно сначала скастовать — активируется на
 *    EFFECT_DURATION_TURNS ходов через тот же activeEffects-механизм, что
 *    и баффы/дебаффы (lib/combat-effects.ts).
 *
 * 6. "Усиление последующих дебаффов" (rotting-mark) — "Все последующие
 *    дебаффы на враге сильнее на N%" — тоже активируется кастом на
 *    EFFECT_DURATION_TURNS ходов, умножает resolution.enemyDamageReduction
 *    для дебафф-способностей, скастованных, пока эффект активен.
 *
 * Из 40 активных способностей в игре с нетривиальным триггером категории
 * 1-6 (3 + 13 + 5 = 21) реализованы здесь как шесть переиспользуемых
 * составных примитивов. Остальные 19 сознательно НЕ реализованы — каждая
 * требует своей уникальной, не переиспользуемой механики или блокируется
 * структурным отсутствием механики в движке:
 * - Перенаправление урона союзника на себя (tornak-wall, living-fortress,
 *   orc-living-shield, grumgar-wall) и воскрешение союзника (return-to-roots) —
 *   союзников в игре не существует, self-подстановка (как для аур-пассивок)
 *   здесь невозможна: нельзя "перенаправить свой урон на себя" или
 *   "воскресить себя, уже стоя живым в бою".
 * - "Если убивает — следующий удар усилен" (rending-strike, dismemberment) —
 *   бой заканчивается вместе со смертью врага (в игре один враг за бой), то
 *   есть "следующему удару" просто неоткуда взяться в рамках того же боя —
 *   тот же структурный тупик, что и у soul-harvest/on_victory_damage_buff
 *   среди пассивок (см. lib/passive-runtime.ts).
 * - Стойки, требующие выбора игроком (moon-cycle) — нужен отдельный UI-выбор
 *   из нескольких вариантов, а не единственный числовой параметр.
 * - Связка двух персонажей (interweaving, fire-communion) — второго
 *   персонажа для связки не существует.
 * - Урон "от проклятия" как лечение (the-abyss) — как и у shadow-of-the-deep
 *   среди пассивок, отдельного типа урона "проклятие" в движке нет.
 * - Многоударная серия за один каст (the-slaughter) — resolveAbility()
 *   рассчитан на один результат за каст, не на серию из N ударов.
 * - Авто-масштабирование силы эффекта по ходам (infection) — как и у
 *   plague-amplification среди пассивок, нужно отслеживать нарастающую
 *   магнитуду отдельно для каждого наложенного эффекта.
 * - Танк-провокация (bone-fortress) — управления вниманием/целью врага
 *   (кого он атакует) в движке не существует, враг всегда бьёт игрока.
 * - Накопление щита за "пропущенные удары" (blood-oath) и рекуррентный
 *   бонус "каждые N ударов" вне уже покрытых passive-примитивов
 *   (battle-tempo) — оставлены как честный остаток: реализуемо, но
 *   каждое требует своего нового состояния ради ровно одной способности,
 *   не окупая сложность в рамках уже большого объёма этого прохода.
 * - Автоматические ловушки в начале хода врага (double-trap) — реализуемо
 *   через уже существующий per-round tick, но тоже единственный потребитель
 *   на новое поле состояния — тот же компромисс, что и выше.
 */

export interface DeathWardEffect {
  healPercent: number;
  shieldPercent: number;
}

/** Разбирает описание активной способности в оберег от смерти, если это он (иначе null). */
export function parseDeathWard(description: string): DeathWardEffect | null {
  const d = description;
  if (!/при (получении смертельного урона|получении смертельного удара|смертельном ударе)/i.test(d)) return null;
  if (!/выживает с 1\s*хп/i.test(d)) return null;

  const healM = d.match(/восстанавливает\s*(\d+)\s*%\s*хп/i);
  const shieldM = d.match(/получает щит\s*(\d+)\s*%/i);

  return {
    healPercent: healM ? parseInt(healM[1], 10) / 100 : 0,
    shieldPercent: shieldM ? parseInt(shieldM[1], 10) / 100 : 0,
  };
}

export interface ArmedEffectSpec {
  kind: 'reduce_next_incoming' | 'boost_next_outgoing' | 'next_attack_crit' | 'next_attack_lifesteal' | 'next_attack_ignore_defense';
  percent: number;
}

/** Разбирает описание активной способности в один или несколько "заряженных" одноразовых эффектов (иначе []). */
export function parseArmedEffects(description: string): ArmedEffectSpec[] {
  const d = description;
  // "Если убивает" — эффект зависит от исхода этой же атаки, не безусловный заряд.
  // "Каждые N ударов" — рекуррентный триггер, а не одноразовый заряд.
  if (/если убивает/i.test(d) || /кажд[а-яё]+\s*\d+[-\s]?[а-яё]*\s*удар/i.test(d)) return [];

  const effects: ArmedEffectSpec[] = [];

  // Снижает урон следующего (получаемого) удара на N% — оба порядка слов
  // ("урон следующего удара" и "следующий получаемый урон").
  {
    const m = d.match(/снижа[а-яё]*\s*(урон\s*)?следующ[а-яё]*\s*(получаем[а-яё]*\s*)?удар[а-яё]*\s*(врага\s*)?на\s*(\d+)\s*%/i)
      || d.match(/снижа[а-яё]*\s*следующ[а-яё]*\s*получаем[а-яё]*\s*урон[^.]*?на\s*(\d+)\s*%/i);
    if (m) effects.push({ kind: 'reduce_next_incoming', percent: parseInt(m[m.length - 1], 10) / 100 });
  }
  // Блокирует/поглощает следующую атаку/удар полностью.
  if (/(блокирует|поглощает)[^.]*следующ[а-яё]*\s*(атак[а-яё]*|удар[а-яё]*)/i.test(d) && !effects.some(e => e.kind === 'reduce_next_incoming')) {
    effects.push({ kind: 'reduce_next_incoming', percent: 1 });
  }

  // Следующая атака наносит +N% урона (или "дополнительный урон ... равный N%" без явного "+").
  {
    const m = d.match(/следующ[а-яё]*\s*(атак[а-яё]*|удар[а-яё]*)[^.]*?\+\s*(\d+)\s*%\s*урон/i)
      || d.match(/следующ[а-яё]*\s*атак[а-яё]*\s*наносит\s*дополнительн[а-яё]*\s*урон[^.]*?равн[а-яё]*\s*(\d+)\s*%/i);
    if (m) effects.push({ kind: 'boost_next_outgoing', percent: parseInt(m[m.length - 1], 10) / 100 });
  }
  // Следующая атака наносит -N% урона (штраф-условие, напр. obsidian-plating).
  {
    const m = d.match(/следующ[а-яё]*\s*атак[а-яё]*\s*наносит\s*-\s*(\d+)\s*%\s*урон/i);
    if (m) effects.push({ kind: 'boost_next_outgoing', percent: -parseInt(m[1], 10) / 100 });
  }
  // Следующая атака — гарантированный крит.
  if (/следующ[а-яё]*\s*атак[а-яё]*\s*\+\s*\d+\s*%\s*крит/i.test(d)) {
    effects.push({ kind: 'next_attack_crit', percent: 0 });
  }
  // Следующая атака лечит на N% от нанесённого урона.
  {
    const m = d.match(/следующ[а-яё]*\s*атак[а-яё]*\s*лечит[^.]*?(\d+)\s*%/i);
    if (m) effects.push({ kind: 'next_attack_lifesteal', percent: parseInt(m[1], 10) / 100 });
  }
  // Следующая атака игнорирует N% брони цели.
  {
    const m = d.match(/следующ[а-яё]*\s*атак[а-яё]*\s*игнорирует\s*(\d+)\s*%\s*брон/i);
    if (m) effects.push({ kind: 'next_attack_ignore_defense', percent: parseInt(m[1], 10) / 100 });
  }

  return effects;
}

export interface ImmediateSelfBuff {
  ignoreDefensePercent: number;
  guaranteedCrit: boolean;
  cooldownTurns: number;
}

/**
 * "Игнорирует N% брони [+ гарантированный крит] (КД N ходов)" — эффект на ЭТОТ
 * каст (в отличие от ArmedEffectSpec выше, который про СЛЕДУЮЩИЙ каст).
 */
export function parseImmediateSelfBuff(description: string): ImmediateSelfBuff | null {
  const d = description;
  // "следующая" — это ArmedEffectSpec, не сюда. "либо" — ветвление с выбором,
  // не поддерживается (напр. slant-strike: "игнорирует 25% брони, либо...").
  // "на N ход" — многоходовой дебафф НА ВРАГА (напр. crack), а не одноразовый
  // бонус этому касту — КД тоже "N ходов", но без предлога "на" перед числом.
  if (/следующ/i.test(d) || /либо/i.test(d) || /на\s*\d+\s*ход/i.test(d)) return null;

  const ignoreM = d.match(/игнорирует\s*(\d+)\s*%\s*брон/i);
  const guaranteedCrit = /гарантированн[а-яё]*\s*крит/i.test(d);
  const cdM = d.match(/КД\s*(\d+)\s*ход/i);
  if (!ignoreM && !guaranteedCrit) return null;

  return {
    ignoreDefensePercent: ignoreM ? parseInt(ignoreM[1], 10) / 100 : 0,
    guaranteedCrit,
    cooldownTurns: cdM ? parseInt(cdM[1], 10) : 0,
  };
}

export interface ExecuteEffect {
  thresholdPercent: number;
}

/**
 * "Если у врага ниже N% ХП — мгновенная казнь (PvE: порог M%, казнь только
 * не-боссов; PvP: ...)". PvP-ветка игнорируется — в игре нет PvP.
 */
export function parseExecute(description: string): ExecuteEffect | null {
  const m = description.match(/PvE:\s*порог\s*(\d+)\s*%[^;]*казнь только не-боссов/i);
  if (!m) return null;
  return { thresholdPercent: parseInt(m[1], 10) / 100 };
}

export interface ActivatedOnBlockCounter {
  percent: number;
}

/**
 * "После блокировки/блока удара наносит контрудар равный N% поглощённого" —
 * активируется кастом на EFFECT_DURATION_TURNS ходов (см. combat-engine.ts),
 * в отличие от одноимённых ПАССИВОК tornak-foundation/bone-spike, которые
 * действуют всегда без каста — см. lib/passive-runtime.ts.
 */
export function parseActivatedOnBlockCounter(description: string): ActivatedOnBlockCounter | null {
  if (!/после блок/i.test(description)) return null;
  const m = description.match(/(\d+)\s*%\s*(от\s*)?поглощ[а-яё]*/i);
  if (!m) return null;
  return { percent: parseInt(m[1], 10) / 100 };
}

export interface DebuffAmplify {
  percent: number;
}

/** "Все последующие дебаффы на враге сильнее на N%" — активируется кастом на EFFECT_DURATION_TURNS ходов. */
export function parseDebuffAmplify(description: string): DebuffAmplify | null {
  const m = description.match(/послед[а-яё]*\s*дебафф[а-яё]*\s*(на враге\s*)?сильнее на\s*(\d+)\s*%/i);
  if (!m) return null;
  return { percent: parseInt(m[2], 10) / 100 };
}

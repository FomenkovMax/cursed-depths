function pick(pool: string[]): string {
  return pool[Math.floor(Math.random() * pool.length)];
}

export function goldFindMessage(locationId: string, gold: number): string {
  const pool = LOCATION_FLAVOR[locationId]?.goldFind ?? DEFAULT_FLAVOR.goldFind;
  return pick(pool).replace('{gold}', String(gold));
}

export function encounterMessage(locationId: string, enemyId: string, enemyNameRu: string): string {
  if (BOSS_INTRO[enemyId]) return BOSS_INTRO[enemyId];
  const pool = LOCATION_FLAVOR[locationId]?.encounterLead ?? DEFAULT_FLAVOR.encounterLead;
  return pick(pool).replace('{enemy}', enemyNameRu);
}

